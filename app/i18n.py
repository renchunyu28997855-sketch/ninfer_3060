def set_lang(code: str) -> str:
    """切换语言（"zh"/"en"，非法值回退 zh），返回生效值。"""
    global _LANG
    _LANG = code if code in ("zh", "en") else "zh"
    return _LANG


def bootstrap(config_path: str):
    """模块加载期调用：从 config.json 读 ui_lang 并 set_lang；失败保持默认中文。"""
    import json as _json
    try:
        with io.open(config_path, encoding="utf-8") as _f:
            set_lang(_json.load(_f).get("ui_lang", "zh"))
    except Exception:
        pass


def lang() -> str:
    return _LANG


def t(key: str, **fmt) -> str:
    """取当前语言模板；缺键回退中文；仍缺返回 key。"""
    table = EN if _LANG == "en" else ZH
    s = table.get(key)
    if s is None:
        s = ZH.get(key, key)
    if fmt:
        try:
            s = s.format(**fmt)
        except (KeyError, IndexError, ValueError):
            pass
    return s


def fmt(n) -> str:
    """按当前语言选 token 单位格式（zh=万/亿，en=k/M/B）。"""
    from stats_store import fmt_tokens, fmt_tokens_en
    return (fmt_tokens if _LANG == "zh" else fmt_tokens_en)(n)
